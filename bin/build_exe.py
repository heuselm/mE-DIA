#!/usr/bin/env python3
"""
Build mEDIA.exe into the repository root (one level above bin/).

  python bin/build_exe.py [--lean] [--with-portable-python]

Default is a SELF-CONTAINED build: pandas + matplotlib and a copy of the
pipeline sources are bundled, so the only external requirement on the target
machine is DIA-NN itself. Pass --lean for a smaller .exe that relies on a
system Python with pandas + matplotlib installed.

Resulting layout:
  mEDIA.exe                    ← repo root, double-click to launch
  bin/run_pipeline.py          ← found via <exe_dir>/bin/ by server.py
  bin/proteoform_analysis.py   ← imported by run_pipeline.py
  bin/viewer/viewer.html       ← peptide mapper template, copied into results

The pipeline sources stay on disk rather than inside the bundle, so they can
be patched without rebuilding the .exe.

Pass --with-portable-python to assemble python_portable/ next to the .exe
(embeddable Python + pandas + matplotlib pre-installed, ~150 MB download +
install). server.py prefers it when present; otherwise falls back to system
Python.
"""
import argparse
import datetime as _dt
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import build_info as _bi  # noqa: E402

# Python 3.14 on Windows still defaults stdout to cp1252; reconfigure so
# Unicode in our print messages doesn't crash when stdout is captured.
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

ROOT    = Path(__file__).parent.parent   # repository root (holds mEDIA.exe)
BIN     = ROOT / "bin"
UI_DIST = BIN / "ui" / "dist"
DIST    = ROOT / "dist"                  # build output, gitignored


def check_ui(allow_stale: bool = False):
    if not (UI_DIST / "index.html").exists():
        print("ERROR: React UI not built.")
        print("  Run first:  cd bin/ui && npm run build")
        sys.exit(1)
    # A stale dist is how another branch's GUI gets bundled: dist/ is gitignored,
    # so switching branches changes src/ and leaves the built assets behind.
    newest_src = max((f.stat().st_mtime for f in (BIN / "ui" / "src").rglob("*")
                      if f.is_file()), default=0)
    dist_built = max((f.stat().st_mtime for f in UI_DIST.rglob("*")
                      if f.is_file()), default=0)
    if newest_src > dist_built:
        when = _dt.datetime.fromtimestamp(dist_built).strftime("%Y-%m-%d %H:%M")
        print(f"ERROR: bin/ui/dist ({when}) is older than bin/ui/src.")
        print("  The build would bundle a GUI that does not match this checkout.")
        print("  Run:  cd bin/ui && npm run build")
        print("  Or pass --allow-stale-ui if that is really what you want.")
        if not allow_stale:
            sys.exit(1)
        print("  [warn] --allow-stale-ui given; continuing with the stale GUI")
    print(f"[OK] React UI dist found: {UI_DIST}")


def stamp_build_info(allow_dirty: bool = False) -> dict:
    """Write bin/_build_info.py (generated, gitignored) and return the dict."""
    info = _bi.from_git(cwd=str(ROOT))
    if info.get("dirty") and not allow_dirty:
        print("ERROR: the working tree has uncommitted changes.")
        print("  A build from a dirty tree cannot be traced back to a commit.")
        print("  Commit or stash first, or pass --allow-dirty to stamp it as dirty.")
        sys.exit(1)
    ui_built = max((f.stat().st_mtime for f in UI_DIST.rglob("*") if f.is_file()),
                   default=0)
    info["built_utc"] = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    info["ui_built_utc"] = (
        _dt.datetime.fromtimestamp(ui_built, _dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        if ui_built else _bi.UNKNOWN)
    info["self_contained"] = True            # overwritten by build_exe()
    target = BIN / "_build_info.py"
    target.write_text(
        '"""Generated by bin/build_exe.py at build time. Not tracked by git."""\n'
        f"BUILD_INFO = {info!r}\n", encoding="utf-8")
    print(f"[OK] stamped {target.name}: {_bi.one_line(info)}")
    return info


def ensure_pyinstaller():
    try:
        import PyInstaller  # noqa: F401
        print("[OK] PyInstaller found")
    except ImportError:
        print("[..] Installing PyInstaller...")
        subprocess.run([sys.executable, "-m", "pip", "install", "pyinstaller"],
                       check=True)


def build_exe(self_contained: bool = True, info: dict | None = None,
              also_plain: bool = False):
    sep = ";" if sys.platform == "win32" else ":"
    info = info or _bi.get()
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--onefile",
        "--name", "mEDIA",
        "--distpath", str(DIST),
        "--workpath", str(ROOT / "build"),
        "--specpath", str(ROOT / "build"),
        f"--add-data={UI_DIST}{sep}ui/dist",
        f"--add-data={BIN / '_build_info.py'}{sep}.",
        "--hidden-import", "build_info",
        "--hidden-import", "uvicorn.lifespan.on",
        "--hidden-import", "uvicorn.lifespan.off",
        "--hidden-import", "uvicorn.protocols.websockets.auto",
        "--hidden-import", "uvicorn.protocols.websockets.websockets_impl",
        "--hidden-import", "uvicorn.protocols.http.auto",
        "--hidden-import", "uvicorn.protocols.http.h11_impl",
        "--hidden-import", "uvicorn.logging",
        "--hidden-import", "tkinter",
        "--hidden-import", "tkinter.filedialog",
    ]

    if self_contained:
        # Bundle the pipeline's own dependencies and a copy of its sources, so a
        # bare mEDIA.exe runs with nothing installed but DIA-NN. server.py then
        # re-invokes the .exe as its own interpreter (--exec-script).
        cmd += [
            "--hidden-import", "pandas",
            "--hidden-import", "matplotlib",
            "--hidden-import", "matplotlib.backends.backend_pdf",
            "--hidden-import", "matplotlib.backends.backend_agg",
            "--collect-data", "matplotlib",
            f"--add-data={BIN / 'run_pipeline.py'}{sep}.",
            f"--add-data={BIN / 'build_info.py'}{sep}.",
            f"--add-data={BIN / 'wslpaths.py'}{sep}.",
            f"--add-data={BIN / 'proteoform_analysis.py'}{sep}.",
            f"--add-data={BIN / 'viewer' / 'viewer.html'}{sep}viewer",
        ]

    cmd.append(str(BIN / "server.py"))
    print(f"\n[..] Running PyInstaller ({'self-contained' if self_contained else 'lean'})...\n")
    DIST.mkdir(parents=True, exist_ok=True)
    subprocess.run(cmd, check=True)

    # Name the artifact after what is in it. PyInstaller writes mEDIA.exe;
    # rename to mEDIA-<branch>-<sha>[-dirty].exe inside dist/.
    produced = DIST / ("mEDIA.exe" if sys.platform == "win32" else "mEDIA")
    final = DIST / _bi.artifact_name(info, ext=produced.suffix)
    if produced.exists():
        if final.exists():
            final.unlink()
        produced.rename(final)
    if also_plain:
        plain = ROOT / produced.name
        shutil.copy2(final, plain)
        print(f"[OK] copied to {plain} (convenience name; provenance is inside)")
    return final


def build_portable_python():
    script = BIN / "build_portable_python.py"
    if not script.exists():
        print(f"  [warn] {script} not found; skipping.")
        return
    print("\n[..] Building portable Python (one-time, ~150 MB)...\n")
    subprocess.run([sys.executable, str(script), "--out", str(ROOT / "python_portable")],
                   check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lean", action="store_true",
                    help="Build without pandas/matplotlib bundled (~59 MB). "
                         "Requires Python + pandas + matplotlib on the target machine.")
    ap.add_argument("--with-portable-python", action="store_true",
                    help="Also assemble python_portable/ (embeddable Python + pandas). "
                         "Not needed for the default self-contained build.")
    ap.add_argument("--skip-exe", action="store_true",
                    help="Skip PyInstaller (use to only run --with-portable-python).")
    ap.add_argument("--allow-dirty", action="store_true",
                    help="Build from a tree with uncommitted changes; the artifact "
                         "is stamped and named '-dirty'.")
    ap.add_argument("--allow-stale-ui", action="store_true",
                    help="Build even if bin/ui/dist is older than bin/ui/src.")
    ap.add_argument("--also-plain", action="store_true",
                    help="Additionally copy the artifact to ./mEDIA.exe for daily use.")
    args = ap.parse_args()

    artifact = None
    if not args.skip_exe:
        check_ui(allow_stale=args.allow_stale_ui)
        ensure_pyinstaller()
        info = stamp_build_info(allow_dirty=args.allow_dirty)
        info["self_contained"] = not args.lean
        artifact = build_exe(self_contained=not args.lean, info=info,
                             also_plain=args.also_plain)

    if args.with_portable_python:
        build_portable_python()

    print(f"""
Build complete!

  {artifact or (DIST / 'mEDIA.exe')}   (launch this; name carries branch + commit)
  {BIN / 'run_pipeline.py'}        (source, found by the .exe automatically)
  {BIN / 'proteoform_analysis.py'} (source, imported by run_pipeline.py)
  {BIN / 'viewer' / 'viewer.html'} (template, copied into result folders)
  {ROOT / 'python_portable'}  {'(built)' if args.with_portable_python else '(NOT built - pass --with-portable-python)'}
""")


if __name__ == "__main__":
    main()
